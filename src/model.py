"""
model.py — Архитектура нейросети для распознавания жестов КЖЯ

КАК ЭТО РАБОТАЕТ (для защиты перед жюри):
===========================================

Наша задача: получить последовательность кадров (30 кадров, каждый = 63 числа)
и определить, какой ЖЕСТ показан. Это задача КЛАССИФИКАЦИИ ПОСЛЕДОВАТЕЛЬНОСТЕЙ.

Почему мы используем LSTM, а не обычную нейросеть?
    Обычная нейросеть (Dense) обрабатывает каждый кадр ОТДЕЛЬНО.
    Но жест — это ДВИЖЕНИЕ, то есть важна последовательность кадров.
    
    LSTM (Long Short-Term Memory) — это тип нейросети, который умеет
    «запоминать» информацию из предыдущих кадров. Представьте, что вы
    смотрите видео: чтобы понять жест, вам нужно видеть НЕ один кадр,
    а всю последовательность движений. LSTM делает то же самое.

    Аналогия: чтение предложения. Чтобы понять слово, вам нужно помнить
    предыдущие слова. LSTM — это нейросеть, которая «читает» кадры
    жеста один за другим и помнит контекст.

Что такое Bidirectional?
    Обычный LSTM читает кадры СЛЕВА НАПРАВО (от начала к концу).
    Bidirectional LSTM читает И СЛЕВА НАПРАВО, И СПРАВА НАЛЕВО.
    
    Зачем? Представьте, что вы смотрите видео жеста «привет».
    Рука поднимается, а потом опускается. Если смотреть только вперёд,
    модель не знает, ЧТО будет дальше. Если смотреть и назад — она
    знает, что после подъёма будет опускание. Это даёт больше контекста.

Что такое Masking?
    Мы дополнили короткие видео нулями до 30 кадров (padding).
    Masking говорит нейросети: «Эти нули — не настоящие данные, 
    ИГНОРИРУЙ их». Без Masking нейросеть пыталась бы учиться
    на нулях и делала бы ошибки.

Что такое Dropout?
    Во время обучения мы СЛУЧАЙНО «выключаем» 30% нейронов.
    Это заставляет нейросеть НЕ полагаться на одни и те же нейроны,
    а распределять знания по всей сети. Это борьба с ПЕРЕОБУЧЕНИЕМ.
    
    Переобучение — это когда модель ЗАЗУБРИВАЕТ обучающие данные,
    как ученик, который выучил ответы на тест, но не понимает предмет.
    Dropout заставляет модель ПОНИМАТЬ, а не зазубривать.

Что такое Softmax?
    Последний слой превращает выход нейросети в ВЕРОЯТНОСТИ.
    Например: [0.85, 0.10, 0.05] означает «85% — это жест 'привет',
    10% — 'спасибо', 5% — 'пожалуйста'». Сумма всегда равна 1.0.
"""

import os
import sys

# Добавляем корневую папку проекта в путь импорта
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

import config

# Импорт TensorFlow и Keras
# TensorFlow — это библиотека от Google для создания нейросетей.
# Keras — это высокоуровневый API внутри TensorFlow, который делает
# построение моделей простым и понятным (как конструктор LEGO).
import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import (
    Masking,
    LSTM,
    Bidirectional,
    Dropout,
    Dense,
)


def create_model(num_classes: int,
                 sequence_length: int = None,
                 num_features: int = None) -> tf.keras.Model:
    """
    Создаёт модель нейросети для классификации жестов.

    Архитектура (послойно):
        1. Masking       — игнорирует padding-нули
        2. BiLSTM (64)   — двунаправленный LSTM, 64 нейрона
        3. Dropout (0.3) — «выключает» 30% нейронов для борьбы с переобучением
        4. BiLSTM (32)   — второй LSTM для более глубокого анализа
        5. Dense (32)    — полносвязный слой, извлекает финальные признаки
        6. Dense (N)     — выходной слой, N = количество жестов (классов)

    Аргументы:
        num_classes (int): Количество различных жестов для распознавания.
            Например, если мы учим модель распознавать 10 жестов, num_classes=10.
        sequence_length (int): Количество кадров в последовательности (по умолчанию 30).
        num_features (int): Количество признаков на кадр (по умолчанию 63 = 21×3).

    Возвращает:
        tf.keras.Model: Скомпилированная модель, готовая к обучению.
    """
    # Используем значения из config.py, если не указаны явно
    if sequence_length is None:
        sequence_length = config.SEQUENCE_LENGTH  # 30
    if num_features is None:
        num_features = config.TOTAL_FEATURES  # 21 × 3 × 2 = 126 (2 руки)

    print(f"\n{'=' * 50}")
    print(f"Создание модели нейросети")
    print(f"  Количество классов (жестов): {num_classes}")
    print(f"  Длина последовательности:    {sequence_length} кадров")
    print(f"  Признаков на кадр:           {num_features}")
    print(f"{'=' * 50}\n")

    # ============================================================
    # Строим модель слой за слоем (Sequential = последовательная)
    # ============================================================
    # Sequential означает, что данные проходят через слои ОДИН ЗА ДРУГИМ,
    # как вода по трубе: вход → слой 1 → слой 2 → ... → выход.

    model = Sequential(name="KZH_Sign_Classifier")

    # ----------------------------------------------------------
    # СЛОЙ 1: Masking — маска для padding-нулей
    # ----------------------------------------------------------
    # Вход модели: тензор формы (batch_size, sequence_length, num_features)
    #   batch_size — сколько примеров обрабатываем одновременно
    #   30 — количество кадров (временных шагов)
    #   num_features обычно 162: две руки плюс выбранные точки лица
    #
    # mask_value=0.0 означает: если ВСЕ признаки кадра равны 0,
    # этот кадр — padding, и его нужно ИГНОРИРОВАТЬ.
    # Это критично для коротких видео, которые мы дополнили нулями.
    model.add(Masking(
        mask_value=0.0,
        input_shape=(sequence_length, num_features),
        name="masking_padding"
    ))
    print("  [1/6] Masking(mask_value=0.0) — игнорируем padding-нули")

    # ----------------------------------------------------------
    # СЛОЙ 2: Bidirectional LSTM — двунаправленная память
    # ----------------------------------------------------------
    # LSTM с 64 нейронами читает последовательность в обоих направлениях.
    #
    # 64 нейрона — это размер «памяти». Больше нейронов = больше
    # информации может запомнить, но и больше риск переобучения.
    # 64 — хороший баланс для нашего объёма данных.
    #
    # return_sequences=True — LSTM возвращает выход на КАЖДОМ шаге
    # (нам это нужно, чтобы передать всю последовательность
    # во ВТОРОЙ слой LSTM).
    #
    # Bidirectional удваивает выход: 64 вперёд + 64 назад = 128.
    model.add(Bidirectional(
        LSTM(64, return_sequences=True),
        name="bilstm_1"
    ))
    print("  [2/6] Bidirectional(LSTM(64)) — читаем жест в обоих направлениях")

    # ----------------------------------------------------------
    # СЛОЙ 3: Dropout — защита от переобучения
    # ----------------------------------------------------------
    # Во время каждой итерации обучения случайно «выключаем» 30%
    # нейронов. Это заставляет оставшиеся нейроны работать лучше
    # и не позволяет модели «запоминать» обучающие данные наизусть.
    #
    # 0.3 = 30% — стандартное значение. Если модель переобучается,
    # можно увеличить до 0.4–0.5. Если недообучается — уменьшить.
    #
    # ВАЖНО: Dropout работает ТОЛЬКО во время обучения.
    # При предсказании (inference) все нейроны включены.
    model.add(Dropout(0.3, name="dropout"))
    print("  [3/6] Dropout(0.3) — выключаем 30% нейронов против переобучения")

    # ----------------------------------------------------------
    # СЛОЙ 4: Второй Bidirectional LSTM — глубокий анализ
    # ----------------------------------------------------------
    # Второй слой LSTM «читает» ВЫХОД первого слоя.
    # Это даёт модели способность находить более сложные паттерны.
    #
    # 32 нейрона (меньше, чем в первом слое) — это «воронка»:
    # сначала извлекаем много признаков, потом сжимаем
    # до самых важных. Так модель учится выделять СУТЬ жеста.
    #
    # return_sequences=False (по умолчанию) — возвращаем только
    # ПОСЛЕДНИЙ выход. Это финальное «резюме» всей последовательности.
    # Bidirectional: 32 × 2 = 64 выходных нейрона.
    model.add(Bidirectional(
        LSTM(32),
        name="bilstm_2"
    ))
    print("  [4/6] Bidirectional(LSTM(32)) — глубокий анализ паттернов жеста")

    # ----------------------------------------------------------
    # СЛОЙ 5: Dense (полносвязный) — извлечение финальных признаков
    # ----------------------------------------------------------
    # Dense — это «классический» слой нейросети, где КАЖДЫЙ нейрон
    # связан с КАЖДЫМ нейроном предыдущего слоя.
    #
    # activation='relu' (Rectified Linear Unit):
    #   relu(x) = max(0, x)
    #   Если вход отрицательный → выход 0
    #   Если вход положительный → выход = вход
    # Это самая популярная функция активации, потому что она:
    #   - Быстро вычисляется
    #   - Не «убивает» градиент (в отличие от sigmoid)
    #   - Делает модель нелинейной (может находить сложные зависимости)
    model.add(Dense(32, activation="relu", name="dense_features"))
    print("  [5/6] Dense(32, relu) — извлечение финальных признаков жеста")

    # ----------------------------------------------------------
    # СЛОЙ 6: Dense (выходной) — вероятности классов
    # ----------------------------------------------------------
    # Выходной слой имеет столько нейронов, сколько у нас жестов.
    #
    # activation='softmax' превращает «сырые» числа в ВЕРОЯТНОСТИ:
    #   softmax([2.0, 1.0, 0.1]) → [0.659, 0.242, 0.099]
    #   Сумма всегда = 1.0
    #
    # Класс с НАИБОЛЬШЕЙ вероятностью — это предсказание модели.
    model.add(Dense(num_classes, activation="softmax", name="output_classes"))
    print(f"  [6/6] Dense({num_classes}, softmax) — вероятности для {num_classes} жестов")

    # ============================================================
    # Компиляция модели — настраиваем процесс обучения
    # ============================================================
    # optimizer='adam' — алгоритм оптимизации Adam.
    #   Это «умный» способ обновлять веса нейросети.
    #   Adam адаптивно подбирает скорость обучения для КАЖДОГО
    #   параметра. Представьте навигатор, который выбирает
    #   оптимальный маршрут, учитывая пробки на каждой улице.
    #
    # loss='sparse_categorical_crossentropy':
    #   Функция потерь для задачи классификации.
    #   «sparse» — потому что метки у нас целые числа (0, 1, 2...),
    #   а не one-hot векторы ([1,0,0], [0,1,0], [0,0,1]).
    #   Чем ниже loss — тем лучше модель предсказывает.
    #
    # metrics=['accuracy'] — доля правильных ответов.
    #   accuracy = 0.95 означает «модель угадывает 95% жестов».
    model.compile(
        optimizer="adam",
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )

    print(f"\n  Модель скомпилирована: optimizer=Adam, loss=SparseCCE\n")

    # Выводим таблицу архитектуры
    model.summary()

    return model


# ============================================================
# Точка входа — демонстрация модели
# ============================================================
if __name__ == "__main__":
    """
    Запуск: python src/model.py
    Создаёт модель для 5 жестов и выводит архитектуру.
    """
    print("=== Демонстрация архитектуры модели ===\n")

    # Создаём модель для 5 классов (жестов)
    model = create_model(num_classes=5)

    # Подсчёт параметров
    total_params = model.count_params()
    print(f"\nВсего параметров модели: {total_params:,}")
    print(f"  Это числа (веса), которые нейросеть подбирает при обучении.")
    print(f"  Чем больше параметров, тем «умнее» модель, но и тем больше")
    print(f"  данных нужно для обучения.\n")

    print("=== Демонстрация завершена ===")
